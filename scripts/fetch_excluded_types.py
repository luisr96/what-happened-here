"""Write every subclass (P279*) of the excluded P31 classes to the extractor's resources.

Wikidata types items with specific classes (Zeus is a "Greek deity", not a "deity"), so the
extractor matches against all subclasses. Re-run this when a root class is added below:

    python scripts/fetch_excluded_types.py
"""

import datetime
import json
import pathlib
import time
import urllib.error
import urllib.parse
import urllib.request

# category -> root classes; each root is included in its own subclass set.
ROOTS = {
    "fictional": [
        "Q15632617",  # fictional human
        "Q95074",     # fictional character
        "Q15707521",  # fictional battle
        "Q3658341",   # literary character
        "Q4271324",   # mythical character
        "Q13002315",  # legendary figure
        "Q178885",    # deity
        "Q15773347",  # film character
    ],
    # Eons to stages (Zanclean, Q146094): dated in millions of years, not history.
    "geologic": [
        "Q4005761",   # geochronological unit
        "Q4005689",   # chronostratigraphic unit
    ],
    # A club's, league's or player's season (2011-12 Pro12, Q144644). The generic sports season
    # Q27020041 is kept: tournament editions use it (2022 FIFA World Cup, Q284163).
    "season": [
        "Q1539532",   # sports season of a sports club
        "Q131459694", # association football season
        "Q26897352",  # football league season
        "Q5290181",   # domestic association football season
        "Q47465437",  # player season
        "Q137387240", # volleyball season
        "Q76941636",  # college football season
        "Q106562461", # Top 14 season
        "Q116621413", # season of the United Rugby Championship
    ],
}

# Branches the P279* tree pulls in by mistake, removed with all their subclasses.
NOT_EXCLUDED = {
    "geologic": [
        "Q6299544",   # Juan Crow era
        "Q16719003",  # thalassocratic period (history of Majapahit, Q1340213)
        "Q1896735",   # Marian year
        "Q2735933",   # anomalistic year
    ],
}

OUT = (pathlib.Path(__file__).resolve().parent.parent
       / "extractor" / "src" / "main" / "resources" / "excluded-types.tsv")
ENDPOINT = "https://query.wikidata.org/sparql"
HEADERS = {
    "User-Agent": "what-happened-here/0.1 (https://github.com/luisr96/what-happened-here)",
    "Accept": "application/sparql-results+json",
}


def subclasses(roots):
    values = " ".join("wd:" + qid for qid in roots)
    query = f"SELECT DISTINCT ?t WHERE {{ VALUES ?root {{ {values} }} ?t wdt:P279* ?root }}"
    url = ENDPOINT + "?" + urllib.parse.urlencode({"query": query})
    for attempt in range(5):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=HEADERS), timeout=120) as r:
                rows = json.load(r)["results"]["bindings"]
            qids = {row["t"]["value"].rsplit("/", 1)[-1] for row in rows}
            return {qid for qid in qids if qid.startswith("Q")}
        except urllib.error.HTTPError as e:
            if e.code != 429 or attempt == 4:
                raise
            retry_after = e.headers.get("Retry-After", "")
            time.sleep(int(retry_after) if retry_after.isdigit() else 10)


def main():
    lines = [
        "# Generated by scripts/fetch_excluded_types.py on " + datetime.date.today().isoformat(),
        "# Every subclass (P279*) of the excluded P31 classes: <QID>\\t<category>",
    ]
    for category, roots in ROOTS.items():
        found = subclasses(roots)
        kept_out = NOT_EXCLUDED.get(category, [])
        if kept_out:
            found -= subclasses(kept_out)
        missing = set(roots) - found
        if missing:
            raise SystemExit(f"{category}: roots not returned: {sorted(missing)}")
        lines += [f"{qid}\t{category}" for qid in sorted(found, key=lambda q: int(q[1:]))]
        print(f"{category}: {len(found)} classes")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
